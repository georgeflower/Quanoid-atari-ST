#!/usr/bin/env python3
"""levels.txt -> src/levels.h  (verifies brick counts from the web game's comment)."""
import colorsys, sys

ROWS, COLS = 14, 13
src, dst = sys.argv[1], sys.argv[2]

levels = []  # (boss, rows)
cur = None
for line in open(src):
    line = line.rstrip("\n")
    if not line or line.startswith("#"):
        continue
    if line.startswith("L"):
        name, arg = line.split()
        if arg == "B":
            levels.append((True, ["." * COLS] * ROWS, 0))
            cur = None
        else:
            cur = (False, [], int(arg))
            levels.append(cur)
        continue
    assert cur is not None, f"stray row: {line}"
    assert len(line) == COLS and set(line) <= set(".1234"), f"bad row {line!r}"
    cur[1].append(line)

assert len(levels) == 20, len(levels)
for i, (boss, rows, expect) in enumerate(levels, 1):
    assert len(rows) == ROWS, (i, len(rows))
    if not boss:
        got = sum(c != "." for r in rows for c in r)
        assert got == expect, f"L{i}: {got} bricks, web game says {expect}"

# World palettes (game.ts colorPalettes) -> ST 3-bit-per-gun colours
WORLDS = [
    [(0,75,55),(30,85,55),(45,90,55),(200,70,50),(280,60,55),(330,70,55),(120,60,45),(180,65,50)],
    [(15,90,60),(350,85,55),(40,95,60),(25,90,50),(0,85,45),(35,90,55),(10,80,50),(45,85,50)],
    [(300,90,60),(180,85,55),(280,90,65),(190,85,60),(320,85,60),(170,80,55),(290,85,55),(200,90,60)],
    [(120,70,50),(90,75,45),(150,65,45),(60,80,50),(140,70,40),(75,70,45),(160,60,45),(100,65,50)],
]
def st(h, s, l):
    r, g, b = colorsys.hls_to_rgb(h / 360, l / 100, s / 100)
    q = lambda v: min(7, int(round(v * 7)))
    return (q(r) << 8) | (q(g) << 4) | q(b)

with open(dst, "w") as f:
    f.write("/* generated by tools/genlevels.py - do not edit */\n")
    f.write("#define NUM_LEVELS 20\n")
    f.write("static const unsigned char level_is_boss[NUM_LEVELS] = {")
    f.write(",".join("1" if b else "0" for b, _, _ in levels) + "};\n")
    f.write("static const char level_data[NUM_LEVELS][14*13] = {\n")
    for boss, rows, _ in levels:
        s = "".join(rows).replace(".", "0")
        f.write('  {' + ",".join(s) + '},\n')
    f.write("};\n")
    f.write("static const unsigned short world_pal[4][8] = {\n")
    for w in WORLDS:
        f.write("  {" + ",".join("0x%03x" % st(*c) for c in w) + "},\n")
    f.write("};\n")
    # metal hsl(0,0,20) explosive hsl(15,90,50) cracked hsl(40,15,45)
    f.write("#define COL_METAL_RGB 0x%03x\n" % st(0, 0, 20))
    f.write("#define COL_EXPL_RGB 0x%03x\n" % st(15, 90, 50))
    f.write("#define COL_CRACK_RGB 0x%03x\n" % st(40, 15, 45))
print("levels OK:", ", ".join(f"L{i}={'boss' if b else e}" for i, (b, _, e) in enumerate(levels, 1)))
